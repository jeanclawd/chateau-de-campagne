// Snapshot the English originals once so we can switch back and forth.
const EN = {
  places: Object.fromEntries(places.map(p => [p.id, [p.name, p.blurb]])),
  acts: Object.fromEntries(places.flatMap(p => p.acts).map(a => [a.id, [a.name, a.say || '']])),
  toys: toys.map(t => t.name),
  badges: Object.fromEntries(badges.map(b => [b.id, b.name])),
  ranks: ranks.map(r => [r[1], r[2]]),
};

function detect() {
  try { const s = localStorage.getItem('cdc-lang'); if (s && UI[s]) return s; } catch (e) {}
  return (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export let lang = detect();

export function t(key, vars = {}) {
  let s = UI[lang][key] ?? UI.en[key] ?? key;
  if (typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}

export function setLang(l) {
  lang = UI[l] ? l : 'en';
  try { localStorage.setItem('cdc-lang', lang); } catch (e) {}
  const c = { ...EN, ...(CONTENT[lang] || {}) };
  const pick = (tbl, id, en) => (tbl && tbl[id]) || en;
  for (const p of places) {
    [p.name, p.blurb] = pick(c.places, p.id, EN.places[p.id]);
    for (const a of p.acts) { const [n, s] = pick(c.acts, a.id, EN.acts[a.id]); a.name = n; a.say = s || EN.acts[a.id][1]; }
  }
  toys.forEach((toy, i) => { toy.name = pick(c.toys, i, EN.toys[i]); });
  for (const b of badges) b.name = pick(c.badges, b.id, EN.badges[b.id]);
  ranks.forEach((r, i) => { [r[1], r[2]] = pick(c.ranks, i, EN.ranks[i]); });
  UI[lang].days.forEach((d, i) => { DAYS[i] = d; });
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.innerHTML = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-title]')) { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); }
}
